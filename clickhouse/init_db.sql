-- init_db.sql — ClickHouse Schema Initialization for Crypto Analytics Pipeline
-- Creates the 'stocks' database and all required analytical tables.

CREATE DATABASE IF NOT EXISTS stocks;

-- ---------------------------------------------------------------------------
-- 1. Raw Ticks Table (stocks.ticks)
-- Stores every validated trade/ticker event ingested from Coinbase via Kafka.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS stocks.ticks (
    event_id UUID DEFAULT generateUUIDv4(),
    symbol LowCardinality(String),
    price Float64,
    volume Float64,
    timestamp DateTime64(3, 'UTC'),
    price_usd Float64,
    price_inr Nullable(Float64),
    exchange_rate Nullable(Float64),
    rate_timestamp Nullable(DateTime64(3, 'UTC')),
    created_at DateTime DEFAULT now()
) ENGINE = MergeTree()
PARTITION BY toYYYYMM(timestamp)
ORDER BY (symbol, timestamp, price, volume);

-- ---------------------------------------------------------------------------
-- 2. One-Minute Aggregate Table (stocks.ticks_1m_agg)
-- Stores 1-minute windowed metrics computed by Spark Structured Streaming.
-- Uses ReplacingMergeTree(calculated_at) to seamlessly handle late-arriving data updates.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS stocks.ticks_1m_agg (
    symbol LowCardinality(String),
    window_start DateTime64(0, 'UTC'),
    window_end DateTime64(0, 'UTC'),
    event_count UInt64,
    avg_price Float64,
    min_price Float64,
    max_price Float64,
    total_volume Float64,
    avg_price_inr Nullable(Float64),
    calculated_at DateTime DEFAULT now()
) ENGINE = ReplacingMergeTree(calculated_at)
PARTITION BY toYYYYMM(window_start)
ORDER BY (symbol, window_start);

-- ---------------------------------------------------------------------------
-- 3. Market Alerts Table (stocks.market_alerts)
-- Stores anomaly alerts generated by Member 4 (e.g., price spikes, volume surge).
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS stocks.market_alerts (
    alert_id UUID DEFAULT generateUUIDv4(),
    symbol LowCardinality(String),
    alert_type LowCardinality(String),
    severity LowCardinality(String),
    message String,
    metric_value Float64,
    threshold Float64,
    timestamp DateTime64(3, 'UTC'),
    created_at DateTime DEFAULT now()
) ENGINE = MergeTree()
PARTITION BY toYYYYMM(timestamp)
ORDER BY (symbol, timestamp);
